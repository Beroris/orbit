//! Results, JSON and Markdown output, and the regression gate.

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Metric {
    pub name: String,
    pub value: f64,
    pub unit: String,
    /// Whether the regression gate applies. Lower is better for every gated metric.
    pub gated: bool,
}

#[derive(Debug, Default, Serialize, Deserialize)]
pub struct Report {
    pub environment: BTreeMap<String, String>,
    pub metrics: Vec<Metric>,
    /// Things that were checked and passed or failed, with how many times.
    pub checks: Vec<Check>,
    /// Anything that could not be measured here, and why.
    pub not_tested: Vec<String>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Check {
    pub name: String,
    pub passed: u32,
    pub total: u32,
}

impl Report {
    pub fn add(&mut self, name: impl Into<String>, value: f64, unit: &str, gated: bool) {
        self.metrics.push(Metric { name: name.into(), value, unit: unit.to_string(), gated });
    }

    pub fn add_timings(&mut self, name: &str, samples_ms: &[f64], gated: bool) {
        if samples_ms.is_empty() {
            self.not_tested.push(format!("{name}: no samples"));
            return;
        }
        self.add(format!("{name} p50"), percentile(samples_ms, 0.50), "ms", gated);
        self.add(format!("{name} p95"), percentile(samples_ms, 0.95), "ms", gated);
        self.add(format!("{name} p99"), percentile(samples_ms, 0.99), "ms", false);
        self.add(format!("{name} max"), percentile(samples_ms, 1.0), "ms", false);
        self.add(format!("{name} samples"), samples_ms.len() as f64, "count", false);
    }

    pub fn check(&mut self, name: impl Into<String>, passed: u32, total: u32) {
        self.checks.push(Check { name: name.into(), passed, total });
    }

    pub fn to_markdown(&self, comparison: Option<&Comparison>) -> String {
        let mut out = String::from(
            "# Orbit benchmark results\n\nGenerated by `orbit-bench`. Every number below was measured in this run.\n\n## Environment\n\n",
        );
        for (key, value) in &self.environment {
            out.push_str(&format!("- **{key}:** {value}\n"));
        }
        out.push_str("\n## Measurements\n\n| Metric | Value | Unit | Gated |\n|---|---:|---|---|\n");
        for metric in &self.metrics {
            out.push_str(&format!(
                "| {} | {} | {} | {} |\n",
                metric.name,
                format_value(metric.value),
                metric.unit,
                if metric.gated { "yes" } else { "" }
            ));
        }
        if !self.checks.is_empty() {
            out.push_str("\n## Checks\n\n| Check | Passed | Result |\n|---|---:|---|\n");
            for check in &self.checks {
                let result = if check.passed == check.total { "pass" } else { "**FAIL**" };
                out.push_str(&format!("| {} | {}/{} | {} |\n", check.name, check.passed, check.total, result));
            }
        }
        if !self.not_tested.is_empty() {
            out.push_str("\n## Not tested\n\n");
            for item in &self.not_tested {
                out.push_str(&format!("- {item}\n"));
            }
        }
        if let Some(comparison) = comparison {
            out.push_str(&format!(
                "\n## Against the baseline\n\nGate: {:.0}% worse than baseline, plus a small absolute allowance for timer noise.\n\n",
                THRESHOLD * 100.0
            ));
            if comparison.regressions.is_empty() {
                out.push_str("No regressions.\n");
            } else {
                out.push_str("| Regression | Baseline | Now | Change |\n|---|---:|---:|---:|\n");
                for r in &comparison.regressions {
                    // A percentage of zero means nothing, and these metrics can sit at zero.
                    let change = if r.baseline > 0.0 {
                        format!("+{:.0}%", (r.current / r.baseline - 1.0) * 100.0)
                    } else {
                        "was zero".to_string()
                    };
                    out.push_str(&format!(
                        "| {} | {} | {} | {change} |\n",
                        r.name,
                        format_value(r.baseline),
                        format_value(r.current),
                    ));
                }
            }
            if !comparison.missing.is_empty() {
                out.push_str("\nIn the baseline but not measured in this run: ");
                out.push_str(&comparison.missing.join(", "));
                out.push('\n');
            }
        }
        out
    }
}

fn format_value(value: f64) -> String {
    if value == value.trunc() && value.abs() < 1e12 {
        format!("{value:.0}")
    } else if value.abs() >= 100.0 {
        format!("{value:.1}")
    } else {
        format!("{value:.3}")
    }
}

pub fn percentile(samples: &[f64], p: f64) -> f64 {
    if samples.is_empty() {
        return 0.0;
    }
    let mut sorted = samples.to_vec();
    sorted.sort_by(f64::total_cmp);
    let rank = (p * sorted.len() as f64).ceil() as usize;
    sorted[rank.clamp(1, sorted.len()) - 1]
}

pub const THRESHOLD: f64 = 0.15;

#[derive(Debug)]
pub struct Regression {
    pub name: String,
    pub baseline: f64,
    pub current: f64,
}

#[derive(Debug, Default)]
pub struct Comparison {
    pub regressions: Vec<Regression>,
    pub missing: Vec<String>,
}

/// CPU time per minute of idle. `GetProcessTimes` counts in scheduler ticks of about 15.6 ms.
pub const UNIT_CPU_PER_MINUTE: &str = "ms/min";
/// Bytes written per minute of idle.
pub const UNIT_BYTES_PER_MINUTE: &str = "bytes/min";
/// Write operations per minute of idle.
pub const UNIT_WRITES_PER_MINUTE: &str = "writes/min";

/// An allowance for scheduling noise, so a tiny change on a tiny number can't fail a build.
///
/// The idle rates healthily sit at or near zero, where the percentage threshold allows nothing, so
/// they need an allowance of their own. Each is scaled up from a 30 s window: two CPU ticks, and a
/// few small writes, such as one stray database commit. Anything steady goes well past these.
///
/// Timings that cross processes or touch the disk vary by a millisecond or so between clean runs on
/// the same machine, and a trimmed working set by a megabyte or two, depending on what else ran.
/// In-process search timings stay on the tight allowance.
fn allowance(name: &str, unit: &str) -> f64 {
    match unit {
        "ms" if !name.starts_with("search ") => 1.0,
        "KB" if name.contains("working set") => 2048.0,
        "ms" => 0.25,
        "KB" => 256.0,
        UNIT_CPU_PER_MINUTE => 64.0,
        UNIT_BYTES_PER_MINUTE => 64.0 * 1024.0,
        UNIT_WRITES_PER_MINUTE => 20.0,
        _ => 0.0,
    }
}

pub fn compare(baseline: &Report, current: &Report) -> Comparison {
    let mut comparison = Comparison::default();
    for base in baseline.metrics.iter().filter(|m| m.gated) {
        match current.metrics.iter().find(|m| m.name == base.name) {
            Some(now) => {
                if now.value > base.value * (1.0 + THRESHOLD) + allowance(&base.name, &base.unit) {
                    comparison.regressions.push(Regression {
                        name: base.name.clone(),
                        baseline: base.value,
                        current: now.value,
                    });
                }
            }
            None => comparison.missing.push(base.name.clone()),
        }
    }
    comparison
}

#[cfg(test)]
mod tests {
    use super::*;

    fn report(entries: &[(&str, f64, &str, bool)]) -> Report {
        let mut r = Report::default();
        for (name, value, unit, gated) in entries {
            r.add(*name, *value, unit, *gated);
        }
        r
    }

    #[test]
    fn percentile_uses_nearest_rank() {
        let samples: Vec<f64> = (1..=100).map(f64::from).collect();
        assert_eq!(percentile(&samples, 0.50), 50.0);
        assert_eq!(percentile(&samples, 0.95), 95.0);
        assert_eq!(percentile(&samples, 1.0), 100.0);
        assert_eq!(percentile(&[7.0], 0.5), 7.0);
        assert_eq!(percentile(&[], 0.5), 0.0);
    }

    #[test]
    fn gate_fails_only_past_threshold_and_allowance() {
        let base = report(&[("search a", 10.0, "ms", true), ("search b", 10.0, "ms", true), ("c", 10.0, "ms", false), ("open d", 10.0, "ms", true), ("open e", 10.0, "ms", true)]);
        let now = report(&[("search a", 11.7, "ms", true), ("search b", 11.8, "ms", true), ("c", 500.0, "ms", false), ("open d", 12.4, "ms", true), ("open e", 12.6, "ms", true)]);
        let result = compare(&base, &now);
        let names: Vec<&str> = result.regressions.iter().map(|r| r.name.as_str()).collect();
        assert_eq!(names, ["search b", "open e"], "a and d are inside their allowance, b and e are outside, c isn't gated");
    }

    #[test]
    fn noise_on_tiny_numbers_is_allowed() {
        let base = report(&[("search tiny", 0.01, "ms", true)]);
        let now = report(&[("search tiny", 0.2, "ms", true)]);
        assert!(compare(&base, &now).regressions.is_empty());
    }

    #[test]
    fn idle_rates_at_zero_tolerate_noise_but_not_real_work() {
        let base = report(&[
            ("cpu", 0.0, UNIT_CPU_PER_MINUTE, true),
            ("bytes", 0.0, UNIT_BYTES_PER_MINUTE, true),
            ("writes", 0.0, UNIT_WRITES_PER_MINUTE, true),
        ]);
        let noise = report(&[
            ("cpu", 62.5, UNIT_CPU_PER_MINUTE, true),
            ("bytes", 8192.0, UNIT_BYTES_PER_MINUTE, true),
            ("writes", 4.0, UNIT_WRITES_PER_MINUTE, true),
        ]);
        assert!(compare(&base, &noise).regressions.is_empty());

        let busy = report(&[
            ("cpu", 500.0, UNIT_CPU_PER_MINUTE, true),
            ("bytes", 1_000_000.0, UNIT_BYTES_PER_MINUTE, true),
            ("writes", 120.0, UNIT_WRITES_PER_MINUTE, true),
        ]);
        assert_eq!(compare(&base, &busy).regressions.len(), 3);
    }

    #[test]
    fn a_regression_from_zero_has_a_readable_change() {
        let base = report(&[("writes", 0.0, UNIT_WRITES_PER_MINUTE, true)]);
        let now = report(&[("writes", 120.0, UNIT_WRITES_PER_MINUTE, true)]);
        let comparison = compare(&base, &now);
        assert!(now.to_markdown(Some(&comparison)).contains("| writes | 0 | 120 | was zero |"));
    }

    #[test]
    fn missing_metrics_are_reported_not_ignored() {
        let base = report(&[("gone", 1.0, "ms", true)]);
        let result = compare(&base, &Report::default());
        assert_eq!(result.missing, ["gone"]);
        assert!(result.regressions.is_empty());
    }

    #[test]
    fn improvements_never_fail() {
        let base = report(&[("a", 10.0, "ms", true)]);
        let now = report(&[("a", 1.0, "ms", true)]);
        assert!(compare(&base, &now).regressions.is_empty());
    }

    #[test]
    fn markdown_marks_failures() {
        let mut r = report(&[("a", 1.5, "ms", true)]);
        r.check("focus returns", 9, 10);
        r.not_tested.push("thing".to_string());
        let md = r.to_markdown(None);
        assert!(md.contains("| a | 1.500 | ms | yes |"));
        assert!(md.contains("**FAIL**"));
        assert!(md.contains("- thing"));
    }
}
