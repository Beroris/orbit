// Clipboard capture, and text insertion into the focused app.

import AppKit
import Carbon
import COrbit

private let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
private let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
private let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
private let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

/// The pasteboard Orbit reads and writes. Tests point this at a private named pasteboard, so they
/// never touch the owner's real clipboard.
var activePasteboard = NSPasteboard.general

enum ClipCapture: Equatable {
    case skipConcealed, skipExcluded, skipTooLarge, skipEmpty
    case text(String)
    case files([String])
    case image
}

/// Decides what to do with the pasteboard's current contents. Reads metadata before bodies, and
/// reads no body at all for anything it is going to skip.
func evaluatePasteboard(_ pasteboard: NSPasteboard, excluded: [String], sourceName: String?, sourceBundle: String?, captureImages: Bool, maxBytes: Int) -> ClipCapture {
    guard let types = pasteboard.types, !types.isEmpty else { return .skipEmpty }
    if types.contains(concealedType) || types.contains(transientType) || types.contains(autoGeneratedType) {
        return .skipConcealed
    }
    let declaredSource = types.contains(sourceType) ? pasteboard.string(forType: sourceType) : nil
    let names = [sourceName, sourceBundle, declaredSource].compactMap { $0 }
    let isExcluded = names.contains { name in excluded.contains { $0.caseInsensitiveCompare(name) == .orderedSame } }
    if isExcluded { return .skipExcluded }

    if types.contains(.fileURL) {
        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        if !urls.isEmpty { return .files(urls.map(\.path)) }
    }
    if types.contains(.string) {
        guard let text = pasteboard.string(forType: .string), !text.isEmpty else { return .skipEmpty }
        if text.utf8.count > maxBytes { return .skipTooLarge }
        return .text(text)
    }
    if captureImages, types.contains(.png) || types.contains(.tiff) { return .image }
    return .skipEmpty
}

final class ClipboardWatcher {
    // NSPasteboard has no change notification: macOS offers only `changeCount`, so a timer is the
    // only way to notice a copy. It runs only while the user has history turned on and unpaused,
    // and it costs one integer read. It slows down when nothing is being copied and has generous
    // tolerance so the system can coalesce the wakeup with others.
    private static let fastInterval: TimeInterval = 0.75
    private static let slowInterval: TimeInterval = 3

    private var timer: Timer?
    private var lastCount = activePasteboard.changeCount
    private var unchanged = 0
    private var interval = fastInterval
    /// A change count Orbit caused by writing to the pasteboard itself.
    var ownChangeCount = -1
    var skipNext = false
    var onCopy: ((ClipCapture, NSPasteboard, String) -> Void)?
    var limits: () -> (excluded: [String], images: Bool, maxBytes: Int) = { ([], false, 0) }

    var isRunning: Bool { timer != nil }
    var currentInterval: TimeInterval { interval }

    func start() {
        guard timer == nil else { return }
        lastCount = activePasteboard.changeCount
        schedule(ClipboardWatcher.fastInterval)
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func schedule(_ seconds: TimeInterval) {
        interval = seconds
        timer?.invalidate()
        let timer = Timer(timeInterval: seconds, repeats: true) { [weak self] _ in self?.check() }
        timer.tolerance = seconds * 0.5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        let count = activePasteboard.changeCount
        if count == lastCount {
            unchanged += 1
            if unchanged == 40, interval != ClipboardWatcher.slowInterval { schedule(ClipboardWatcher.slowInterval) }
            return
        }
        lastCount = count
        unchanged = 0
        if interval != ClipboardWatcher.fastInterval { schedule(ClipboardWatcher.fastInterval) }
        if count == ownChangeCount { return }
        if skipNext {
            skipNext = false
            return
        }
        let front = NSWorkspace.shared.frontmostApplication
        let isSelf = front?.processIdentifier == ProcessInfo.processInfo.processIdentifier
        let limits = limits()
        let capture = evaluatePasteboard(activePasteboard, excluded: limits.excluded, sourceName: isSelf ? nil : front?.localizedName, sourceBundle: isSelf ? nil : front?.bundleIdentifier, captureImages: limits.images, maxBytes: limits.maxBytes)
        onCopy?(capture, activePasteboard, isSelf ? "" : (front?.localizedName ?? ""))
    }
}

/// PNG bytes and pixel size of the pasteboard's image, if it has one within the size limit.
func pasteboardImagePNG(_ pasteboard: NSPasteboard, maxBytes: Int) -> (Data, Int, Int)? {
    if let png = pasteboard.data(forType: .png), png.count <= maxBytes, let rep = NSBitmapImageRep(data: png) {
        return (png, rep.pixelsWide, rep.pixelsHigh)
    }
    guard let tiff = pasteboard.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff),
          let png = rep.representation(using: .png, properties: [:]), png.count <= maxBytes else { return nil }
    return (png, rep.pixelsWide, rep.pixelsHigh)
}

enum Inserter {
    enum Outcome {
        case inserted
        case onClipboard(String)
    }

    /// Longer text goes to the clipboard for a manual paste, since typing it would take too long
    /// and hold the app's input queue. The same limit as platforms/windows/src/clipboard.rs.
    static let maxTypedUnits = 4 * 1024

    static func writeClipboard(_ text: String) -> Int {
        let pasteboard = activePasteboard
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        return pasteboard.changeCount
    }

    /// May Orbit send keystrokes now? False without the Accessibility grant, and while another app
    /// holds secure input, such as a password field.
    static var canPostKeys: Bool { Permissions.accessibility && Permissions.postEvents && !IsSecureEventInputEnabled() }

    private static func post(key: CGKeyCode, flags: CGEventFlags = []) {
        for isDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: nil, virtualKey: key, keyDown: isDown) else { continue }
            event.flags = flags
            event.setIntegerValueField(.eventSourceUserData, value: injectedTag)
            event.post(tap: .cgSessionEventTap)
        }
    }

    private static func post(text: String) {
        let units = Array(text.utf16)
        var at = 0
        while at < units.count {
            var end = min(at + 16, units.count)
            // Don't split a surrogate pair across two events.
            if end < units.count, UTF16.isLeadSurrogate(units[end - 1]) { end -= 1 }
            var chunk = Array(units[at..<end])
            for isDown in [true, false] {
                guard let event = CGEvent(keyboardEventSource: nil, virtualKey: 0, keyDown: isDown) else { continue }
                event.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: &chunk)
                event.setIntegerValueField(.eventSourceUserData, value: injectedTag)
                event.post(tap: .cgSessionEventTap)
            }
            at = end
        }
    }

    /// Types text through CGEvent, erasing a typed trigger first. Long text is rare and the events
    /// must be spaced, so this runs off the main thread.
    static func type(_ text: String, erase: Int, cursorBack: Int?) {
        for _ in 0..<erase { post(key: 51) }
        var first = true
        for line in text.components(separatedBy: "\n") {
            if !first { post(key: 36) }
            first = false
            if !line.isEmpty { post(text: line) }
            usleep(2000)
        }
        for _ in 0..<(cursorBack ?? 0) { post(key: 123) }
    }

    static func pasteKeystroke() {
        post(key: 9, flags: .maskCommand)
    }
}
